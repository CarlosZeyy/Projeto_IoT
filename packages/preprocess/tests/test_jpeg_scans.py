"""Unit tests for the JPEG scan limit of ``load_image`` (SPEC-024)."""

import io
import struct
from pathlib import Path

import numpy as np
import pytest
from PIL import Image, ImageFile
from PIL.PngImagePlugin import PngInfo

import qc_preprocess
from qc_preprocess import (
    MAX_ASPECT_RATIO,
    MAX_JPEG_SCANS,
    MAX_PIXELS,
    InvalidImageError,
    load_image,
    preprocess,
)
from qc_preprocess import image as image_module

SOS = b"\xff\xda"
EOI = b"\xff\xd9"


def encode(img: Image.Image, fmt: str, **kwargs: object) -> bytes:
    buf = io.BytesIO()
    img.save(buf, fmt, **kwargs)
    return buf.getvalue()


def pattern_image(width: int = 64, height: int = 48, mode: str = "RGB") -> Image.Image:
    """Deterministic test image generated by a fixed formula."""
    y, x = np.mgrid[0:height, 0:width]
    arr = np.stack(
        [(x * 7 + y * 3) % 256, (x * y) % 256, (255 - x * 4 + y * 5) % 256], axis=-1
    ).astype(np.uint8)
    img = Image.fromarray(arr, "RGB")
    return img if mode == "RGB" else img.convert(mode)


def com_segment(payload: bytes) -> bytes:
    """A JPEG COM segment: marker, big-endian length (payload + 2), payload."""
    return b"\xff\xfe" + struct.pack(">H", len(payload) + 2) + payload


def with_com(jpeg: bytes, pairs: int) -> bytes:
    """Insert, right after SOI, a COM segment whose payload is ``pairs`` copies of ``FF DA``."""
    assert jpeg.startswith(b"\xff\xd8")
    return jpeg[:2] + com_segment(SOS * pairs) + jpeg[2:]


def repeated_scans(jpeg: bytes, markers: int) -> bytes:
    """Repeat the last scan of a progressive JPEG until the file has ``markers`` SOS markers."""
    assert jpeg.endswith(EOI)
    last_scan = jpeg[jpeg.rindex(SOS) : -2]
    extra = markers - jpeg.count(SOS)
    assert extra >= 0
    out = jpeg[:-2] + last_scan * extra + EOI
    assert out.count(SOS) == markers
    return out


@pytest.fixture
def baseline_jpeg() -> bytes:
    data = encode(pattern_image(), "JPEG")
    assert data.count(SOS) == 1
    return data


@pytest.fixture
def progressive_jpeg() -> bytes:
    data = encode(pattern_image(256, 256), "JPEG", progressive=True)
    assert 1 < data.count(SOS) <= MAX_JPEG_SCANS
    return data


def test_constant_value_and_reexport() -> None:
    assert MAX_JPEG_SCANS == 64
    assert qc_preprocess.MAX_JPEG_SCANS is image_module.MAX_JPEG_SCANS
    assert "MAX_JPEG_SCANS" in qc_preprocess.__all__
    assert MAX_PIXELS == 40_000_000
    assert MAX_ASPECT_RATIO == 10


@pytest.mark.parametrize(
    ("mode", "size", "kwargs"),
    [
        ("RGB", (64, 48), {}),
        ("RGB", (640, 480), {"progressive": True}),
        ("L", (640, 480), {"progressive": True}),
    ],
)
def test_common_jpegs_accepted(mode: str, size: tuple[int, int], kwargs: dict) -> None:
    data = encode(pattern_image(*size, mode=mode), "JPEG", **kwargs)
    img = load_image(data)
    assert img.mode == "RGB"
    assert img.size == size


def test_limit_is_inclusive(baseline_jpeg: bytes) -> None:
    at_limit = with_com(baseline_jpeg, MAX_JPEG_SCANS - 1)
    assert at_limit.count(SOS) == MAX_JPEG_SCANS
    accepted = preprocess(load_image(at_limit))
    clean = preprocess(load_image(baseline_jpeg))
    assert accepted.tobytes() == clean.tobytes()


def test_one_above_limit_rejected(baseline_jpeg: bytes) -> None:
    above = with_com(baseline_jpeg, MAX_JPEG_SCANS)
    assert above.count(SOS) == MAX_JPEG_SCANS + 1
    with pytest.raises(InvalidImageError, match="JPEG scans") as exc_info:
        load_image(above)
    assert f"{MAX_JPEG_SCANS + 1} scan markers" in str(exc_info.value)


def test_repeated_scans_at_limit_still_decodes(progressive_jpeg: bytes) -> None:
    img = load_image(repeated_scans(progressive_jpeg, MAX_JPEG_SCANS))
    assert img.size == (256, 256)


@pytest.mark.parametrize("markers", [MAX_JPEG_SCANS + 1, 1_000])
def test_repeated_scans_rejected(progressive_jpeg: bytes, markers: int) -> None:
    with pytest.raises(InvalidImageError, match="JPEG scans"):
        load_image(repeated_scans(progressive_jpeg, markers))


def test_markers_after_eoi_are_counted(baseline_jpeg: bytes) -> None:
    # The count covers the whole file, including trailing data such as EXIF thumbnails or MPO.
    with pytest.raises(InvalidImageError, match="JPEG scans"):
        load_image(baseline_jpeg + SOS * MAX_JPEG_SCANS)


def test_path_input_is_checked(tmp_path: Path, baseline_jpeg: bytes) -> None:
    path = tmp_path / "scans.jpg"
    path.write_bytes(with_com(baseline_jpeg, MAX_JPEG_SCANS))
    with pytest.raises(InvalidImageError, match="JPEG scans"):
        load_image(path)


def _spy_open(monkeypatch: pytest.MonkeyPatch) -> list[object]:
    calls: list[object] = []
    real_open = image_module.Image.open

    def spy(*args: object, **kwargs: object) -> Image.Image:
        calls.append(args)
        return real_open(*args, **kwargs)

    monkeypatch.setattr(image_module.Image, "open", spy)
    return calls


def test_rejected_before_image_open(monkeypatch: pytest.MonkeyPatch) -> None:
    calls = _spy_open(monkeypatch)
    header_only = b"\xff\xd8" + com_segment(SOS * (MAX_JPEG_SCANS + 1))
    with pytest.raises(InvalidImageError, match="JPEG scans"):
        load_image(header_only)
    assert calls == []


def test_within_limit_reaches_image_open(monkeypatch: pytest.MonkeyPatch) -> None:
    calls = _spy_open(monkeypatch)
    header_only = b"\xff\xd8" + com_segment(SOS * 10)
    with pytest.raises(InvalidImageError) as exc_info:
        load_image(header_only)
    assert "JPEG scans" not in str(exc_info.value)
    assert len(calls) == 1


def test_png_with_marker_pairs_accepted() -> None:
    info = PngInfo()
    info.add_text("comment", "\xff\xda" * 100)
    data = encode(pattern_image(), "PNG", pnginfo=info)
    assert data.count(SOS) >= 100
    img = load_image(data)
    assert img.size == (64, 48)


@pytest.mark.parametrize(
    "data",
    [
        b"\xff\xd8\x00" + SOS * 100,  # SOI not followed by a marker: not Pillow's JPEG signature
        b"not an image " + SOS * 100,
        b"\x00\xff\xd8\xff" + SOS * 100,  # signature must be at the very start
    ],
)
def test_only_jpeg_signature_is_counted(data: bytes) -> None:
    with pytest.raises(InvalidImageError) as exc_info:
        load_image(data)
    assert "JPEG scans" not in str(exc_info.value)


def test_truncated_flag_checked_before_scans(
    monkeypatch: pytest.MonkeyPatch, baseline_jpeg: bytes
) -> None:
    monkeypatch.setattr(ImageFile, "LOAD_TRUNCATED_IMAGES", True)
    with pytest.raises(RuntimeError, match="LOAD_TRUNCATED_IMAGES"):
        load_image(with_com(baseline_jpeg, MAX_JPEG_SCANS))


def test_empty_checked_before_scans() -> None:
    with pytest.raises(InvalidImageError, match="empty image data"):
        load_image(b"")
