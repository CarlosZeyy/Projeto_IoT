"""Live video mode: state machine, sessions and frame latency (SPEC-019 sections 4.2 to 4.4).

``LiveStateMachine`` turns a stream of inference results into at most one inspection per part:
``IDLE`` -> ``DETECTING`` -> ``EMIT`` -> ``WAIT_REMOVAL`` -> ``IDLE``. ``LiveSessions`` keeps one
machine per page (``session`` field of ``POST /api/live/frame``), and ``FrameLatency`` the numbers
the console shows.

Frames stay in memory only and only while they can still be emitted: never the frame of an
``unknown`` result nor one received in ``WAIT_REMOVAL``, and the kept ones are dropped when they
leave the window, on ``EMIT``, on ``reset`` and at the end of the session (R-02, R-14).
"""

from __future__ import annotations

import math
import threading
from collections import Counter, deque
from collections.abc import Callable
from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Literal

from qc_contracts import Grade, ObjectType
from qc_edge.inference import InferenceResult

LiveState = Literal["IDLE", "DETECTING", "EMIT", "WAIT_REMOVAL"]
LiveEmit = tuple[InferenceResult, bytes, datetime]

# Generated by the page with crypto.getRandomValues; checked with re.fullmatch.
LIVE_SESSION_PATTERN = r"[A-Za-z0-9_-]{16,64}"
LIVE_SESSION_IDLE_S = 60.0
# How often the app drops expired sessions without waiting for the next frame.
LIVE_SWEEP_INTERVAL_S = 5.0
LATENCY_MEMORY = 100

_Pair = tuple[ObjectType, Grade | None]
_EMPTY_TABLE: _Pair = (ObjectType.UNKNOWN, None)


def _pair(result: InferenceResult) -> _Pair:
    return result.object_type, result.grade


@dataclass(frozen=True)
class LiveStep:
    """Outcome of one ``feed``: ``state`` after the step (``EMIT`` on the step that emits)."""

    state: LiveState
    stability: float
    emit: LiveEmit | None = None


@dataclass(slots=True)
class _WindowEntry:
    result: InferenceResult
    frame: bytes | None  # only a frame that can still be emitted
    inspected_at: datetime


class LiveStateMachine:
    """SPEC-019 section 4.2. Not thread-safe: ``LiveSessions`` serializes the calls.

    Raises:
        ValueError: ``window < 1``, ``min_agree`` outside ``1..window``, ``min_confidence``
            outside ``[0, 1]`` or ``empty_frames < 1``.
    """

    def __init__(
        self,
        window: int = 10,
        min_agree: int = 8,
        min_confidence: float = 0.80,
        empty_frames: int = 3,
    ) -> None:
        if window < 1:
            raise ValueError("window must be >= 1")
        if not 1 <= min_agree <= window:
            raise ValueError("min_agree must be from 1 to window")
        if not 0.0 <= min_confidence <= 1.0:
            raise ValueError("min_confidence must be from 0 to 1")
        if empty_frames < 1:
            raise ValueError("empty_frames must be >= 1")
        self._window_size = window
        self._min_agree = min_agree
        self._min_confidence = min_confidence
        self._empty_frames = empty_frames
        self._state: LiveState = "IDLE"
        self._window: deque[_WindowEntry] = deque(maxlen=window)
        self._unknown_run = 0

    @property
    def state(self) -> LiveState:
        """Current state; never ``EMIT``, which only exists in the step that emits."""
        return self._state

    def feed(self, result: InferenceResult, frame: bytes, inspected_at: datetime) -> LiveStep:
        """Process one frame; ``emit`` brings the most recent frame of the stable pair."""
        unknown = result.object_type is ObjectType.UNKNOWN
        if self._state == "IDLE":
            if unknown:
                return LiveStep("IDLE", 0.0)
            self._state = "DETECTING"

        kept = frame if self._state == "DETECTING" and not unknown else None
        self._window.append(_WindowEntry(result, kept, inspected_at))
        self._unknown_run = self._unknown_run + 1 if unknown else 0
        if self._unknown_run >= self._empty_frames:
            self.reset()
            return LiveStep("IDLE", 0.0)

        counts = Counter(_pair(entry.result) for entry in self._window)
        stability = max(counts.values()) / self._window_size
        if self._state == "DETECTING":
            emit = self._stable_frame(counts)
            if emit is not None:
                self._state = "WAIT_REMOVAL"
                for entry in self._window:  # nothing else can be emitted before the next IDLE
                    entry.frame = None
                return LiveStep("EMIT", stability, emit)
        return LiveStep(self._state, stability)

    def reset(self) -> None:
        """Back to ``IDLE``, with the window (and its frames) cleared."""
        self._state = "IDLE"
        self._window.clear()
        self._unknown_run = 0

    def _stable_frame(self, counts: Counter[_Pair]) -> LiveEmit | None:
        """The four conditions of section 4.2, with the window full."""
        if len(self._window) < self._window_size:
            return None
        ranked = counts.most_common(2)
        top, agree = ranked[0]
        if len(ranked) > 1 and ranked[1][1] == agree:
            return None  # a tie at the top is not a stable classification
        if top == _EMPTY_TABLE or agree < self._min_agree:
            return None
        entries = [entry for entry in self._window if _pair(entry.result) == top]
        mean = math.fsum(entry.result.type_confidence for entry in entries) / agree
        if mean < self._min_confidence:
            return None
        latest = entries[-1]
        if latest.frame is None:  # an unknown type with a grade: outside the contract
            return None
        return latest.result, latest.frame, latest.inspected_at


class LiveSessionsFullError(Exception):
    """``LIVE_MAX_SESSIONS`` sessions are active and this one is new (429)."""


@dataclass(slots=True)
class _Session:
    machine: LiveStateMachine
    lot_id: str | None
    last_frame_at: datetime


class LiveSessions:
    """SPEC-019 section 4.3: at most ``max_sessions`` machines, idle ones are discarded.

    Everything runs under one lock, including ``feed`` and ``reset``: two simultaneous requests of
    a session never emit twice. Recording the inspection happens outside it. A clock that went
    backwards restarts the idle count from that instant, so a stopped session never holds a slot
    forever.
    """

    def __init__(
        self,
        clock: Callable[[], datetime],
        *,
        machine_factory: Callable[[], LiveStateMachine] = LiveStateMachine,
        max_sessions: int = 4,
        idle_s: float = LIVE_SESSION_IDLE_S,
    ) -> None:
        self._clock = clock
        self._machine_factory = machine_factory
        self._max_sessions = max_sessions
        self._idle = timedelta(seconds=idle_s)
        self._sessions: dict[str, _Session] = {}
        self._lock = threading.Lock()

    def __len__(self) -> int:
        with self._lock:
            return len(self._sessions)

    def admit(self, session_id: str) -> None:
        """Register a frame of ``session_id``, creating the session when there is room.

        Raises:
            LiveSessionsFullError: the session is new and the maximum was reached.
        """
        with self._lock:
            self._touch(session_id)

    def feed(
        self,
        session_id: str,
        lot_id: str,
        result: InferenceResult,
        frame: bytes,
        inspected_at: datetime,
    ) -> LiveStep:
        """``LiveStateMachine.feed`` of the session; a different ``lot_id`` resets it first.

        The lot is compared here, and not in ``admit``, so a frame whose inference failed changes
        nothing and a window never mixes two lots.

        Raises:
            LiveSessionsFullError: the session expired after ``admit`` and its slot was taken.
        """
        with self._lock:
            session = self._touch(session_id)
            if session.lot_id != lot_id:
                session.machine.reset()
                session.lot_id = lot_id
            return session.machine.feed(result, frame, inspected_at)

    def reset(self, session_id: str) -> None:
        """``LiveStateMachine.reset`` of the session, when it still exists."""
        with self._lock:
            session = self._sessions.get(session_id)
            if session is not None:
                session.machine.reset()

    def sweep(self) -> None:
        """Discard the idle sessions; their frames leave memory now, not at the next request."""
        with self._lock:
            if self._sessions:
                self._expire(self._clock())

    def clear(self) -> None:
        """End every session (app shutdown)."""
        with self._lock:
            for session in self._sessions.values():
                session.machine.reset()
            self._sessions.clear()

    def _touch(self, session_id: str) -> _Session:
        now = self._clock()
        self._expire(now)
        session = self._sessions.get(session_id)
        if session is None:
            if len(self._sessions) >= self._max_sessions:
                raise LiveSessionsFullError
            session = _Session(self._machine_factory(), None, now)
            self._sessions[session_id] = session
        session.last_frame_at = now
        return session

    def _expire(self, now: datetime) -> None:
        for session_id, session in list(self._sessions.items()):
            idle = now - session.last_frame_at
            if idle < timedelta(0):
                session.last_frame_at = now
            elif idle > self._idle:
                session.machine.reset()
                del self._sessions[session_id]


def p95_nearest_rank(values: list[int]) -> int:
    """``sorted(values)[ceil(0.95 * n) - 1]``, in integers (``0.95 * n`` can round up in float).

    Raises:
        ValueError: ``values`` is empty.
    """
    if not values:
        raise ValueError("values must not be empty")
    rank = (95 * len(values) + 99) // 100
    return sorted(values)[rank - 1]


class FrameLatency:
    """``latency_ms`` of the last ``LATENCY_MEMORY`` frames inferred, of every session.

    Only the console reads it (CA-12, step 6): it goes neither to the route nor to the cloud.
    """

    def __init__(self) -> None:
        self._values: deque[int] = deque(maxlen=LATENCY_MEMORY)
        self._lock = threading.Lock()

    def record(self, latency_ms: int) -> None:
        with self._lock:
            self._values.append(latency_ms)

    def summary(self) -> tuple[int, int] | None:
        """``(last, p95)``, or ``None`` before the first frame."""
        with self._lock:
            values = list(self._values)
        if not values:
            return None
        return values[-1], p95_nearest_rank(values)
