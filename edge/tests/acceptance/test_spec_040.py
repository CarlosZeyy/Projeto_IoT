class Blocks(httpx.SyncByteStream):
    """A body delivered block by block: counts what was read and records ``close``."""

    def __init__(self, blocks: Iterable[bytes]) -> None:
        self.blocks = list(blocks)
        self.delivered = 0
        self.closed = False

    def __iter__(self) -> Iterator[bytes]:
        for block in self.blocks:
            self.delivered += 1
            yield block

    def close(self) -> None:
        self.closed = True


def chunks(data: bytes, size: int = 64 * 1024) -> list[bytes]:
    return [data[i : i + size] for i in range(0, len(data), size)] or [b""]


Header = tuple[str | bytes, str | bytes]
Answer = Callable[[httpx.Request], httpx.Response]


class FakeCloud:
    """The cloud with the SPEC-009 idempotency: one row per ``inspection_id``.

    ``answer`` replaces the normal behaviour while set. ``answers_for_batch`` is consumed by the
    next batches only (the health checks keep working).
    """

    def __init__(self) -> None:
        self.stored: dict[str, dict[str, Any]] = {}
        self.writes: list[str] = []
        self.requests: list[httpx.Request] = []
        self.answer: Answer | None = None
        self.answers_for_batch: list[Answer] = []
        self.streams: list[Blocks] = []

    def __call__(self, request: httpx.Request) -> httpx.Response:
        body = request.read()
        self.requests.append(request)
        if self.answer is not None:
            return self.answer(request)
        path = request.url.path
        if path == BATCH_PATH and self.answers_for_batch:
            return self.answers_for_batch.pop(0)(request)
        if path == HEALTH_PATH:
            return httpx.Response(200, json={"status": "ok", "db": "ok"})
        if path == HEARTBEAT_PATH:
            return httpx.Response(204)
        if path == BATCH_PATH:
            return httpx.Response(200, json={"results": self.store(json.loads(body))})
        return httpx.Response(404, json={"detail": "Not Found"})

    def store(self, batch: dict[str, Any]) -> list[dict[str, str]]:
        results = []
        for item in batch["items"]:
            iid = item["inspection_id"]
            if iid in self.stored:
                results.append({"inspection_id": iid, "status": "duplicate"})
            else:
                self.stored[iid] = item
                self.writes.append(iid)
                results.append({"inspection_id": iid, "status": "created"})
        return results

    def streamed(self, status: int, body: bytes | list[bytes], *headers: Header) -> Answer:
        """An answer with a body nobody decodes unless the client reads it."""

        def answer(request: httpx.Request) -> httpx.Response:
            stream = Blocks(chunks(body) if isinstance(body, bytes) else body)
            self.streams.append(stream)
            return httpx.Response(status, stream=stream, headers=[JSON_TYPE, *headers])

        return answer


