def put(root: Path, rel: str, data: bytes) -> Path:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    return path


def snapshot(root: Path) -> dict[str, bytes]:
    """The bytes under ``raw/`` (``--fix`` keeps its empty lock file at the dataset root)."""
    return {
        p.relative_to(root).as_posix(): p.read_bytes()
        for p in sorted((root / "raw").rglob("*"))
        if p.is_file()
    }


@contextmanager
def modes(*pairs: tuple[Path, int]) -> Iterator[None]:
    """Applies the modes and always restores them, so ``tmp_path`` can be removed."""
    saved = [(path, stat.S_IMODE(path.stat().st_mode)) for path, _ in pairs]
    try:
        for path, mode in pairs:
            path.chmod(mode)
        yield
    finally:
        for path, mode in reversed(saved):
            path.chmod(mode)


