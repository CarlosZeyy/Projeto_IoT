def test_extra_ca03_real_socket_identity_on_the_wire_and_bomb_refused(gzip_bomb: bytes) -> None:
    """The real ``httpcore`` path: what the header says on the wire, and the same refusal."""
    _Bomb.bomb = gzip_bomb
    _Bomb.seen = []
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), _Bomb)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        publisher = HttpPublisher(f"http://127.0.0.1:{server.server_address[1]}", new_key())
        peak, raised = peak_of(lambda: publisher.publish_batch([inspection()]))
    finally:
        server.shutdown()
        thread.join(5)
        server.server_close()
    assert type(raised) is PublishTransientError, repr(raised)
    assert str(raised) == REFUSED
    assert peak < PEAK_LIMIT
    assert _Bomb.seen[0]["accept-encoding"] == "identity"


