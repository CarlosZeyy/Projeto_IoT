def peak_of(call: Callable[[], Any]) -> tuple[int, BaseException | None]:
    """Peak of ``tracemalloc`` measured only during ``call``, and what it raised."""
    tracemalloc.start()
    try:
        tracemalloc.reset_peak()
        try:
            call()
        except BaseException as exc:  # noqa: BLE001 - handed to the assertion of the test
            raised: BaseException | None = exc
        else:
            raised = None
        return tracemalloc.get_traced_memory()[1], raised
    finally:
        tracemalloc.stop()


def exception_texts(exc: BaseException) -> str:
    """``str`` and ``repr`` of the exception and of its whole chain."""
    parts: list[str] = []
    seen: list[BaseException] = []
    current: BaseException | None = exc
    while current is not None and current not in seen:
        seen.append(current)
        parts.extend([str(current), repr(current), repr(current.args)])
        current = current.__cause__ or current.__context__
    return "\n".join(parts)


def log_text(caplog: pytest.LogCaptureFixture) -> str:
    parts = [caplog.text]
    for record in caplog.records:
        parts.extend([record.getMessage(), str(record.msg), repr(record.args)])
    return "\n".join(parts)


