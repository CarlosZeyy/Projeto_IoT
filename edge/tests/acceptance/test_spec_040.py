def _privacy_section() -> str:
    """The numbered privacy items of ``edge/README.md`` (the only "section" about the scan)."""
    text = (EDGE_ROOT / "README.md").read_text(encoding="utf-8")
    lines = text.splitlines()
    first = next(i for i, ln in enumerate(lines) if "python -m qc_edge.privacy" in ln)
    start = first
    while start > 0 and re.match(r"\s*\d+\. ", lines[start - 1]):
        start -= 1
    end = first
    while end + 1 < len(lines) and re.match(r"\s*\d+\. ", lines[end + 1]):
        end += 1
    section = "\n".join(lines[start : end + 1])
    assert "varredura" in section
    return section


