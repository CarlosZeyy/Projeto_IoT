def test_ca03_loop_keeps_the_items_and_delivers_them_once(
    rig: Rig, gzip_bomb: bytes, caplog: pytest.LogCaptureFixture
) -> None:
    caplog.set_level(logging.DEBUG)
    items = [inspection(), inspection()]
    for item in items:
        rig.outbox.put(item)
    assert rig.outbox.stats().pending == 2
    rig.cloud.answers_for_batch.append(
        rig.cloud.streamed(200, gzip_bomb, ("content-encoding", "gzip"))
    )

    statuses: list[set[str]] = []
    for _ in range(10):
        rig.loop.run_once()
        statuses.append({r["status"] for r in rig.rows()})
        if rig.outbox.stats().pending == 0:
            break
        rig.clock.advance(MAX_DELAY_S + 1)

    stats = rig.outbox.stats()
    assert stats.pending == 0, statuses
    assert stats.dead == 0
    assert all("dead" not in s for s in statuses), statuses
