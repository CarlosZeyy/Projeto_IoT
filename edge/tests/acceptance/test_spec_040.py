def _compress_blocks(blocks: Iterable[bytes]) -> bytes:
    compressor = zlib.compressobj(9, zlib.DEFLATED, 31)  # 31 = the gzip container
    out = bytearray()
    for block in blocks:
        out += compressor.compress(block)
    out += compressor.flush()
    return bytes(out)


