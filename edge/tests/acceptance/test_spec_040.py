    assert [r["status"] for r in rig.rows()] == ["sent", "sent"]
    assert sorted(rig.cloud.writes) == sorted(str(i.inspection_id) for i in items)
    assert len(rig.cloud.writes) == len(set(rig.cloud.writes)) == 2
    text = log_text(caplog)
    assert REFUSED in text
    assert rig.key not in text
    assert rig.cloud.streams[0].delivered == 0


