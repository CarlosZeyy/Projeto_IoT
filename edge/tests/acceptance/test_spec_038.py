def rowid_of(path: Path, iid: uuid.UUID | str) -> int:
    con = sqlite3.connect(path)
    try:
        (rowid,) = con.execute(
            "SELECT rowid FROM outbox WHERE inspection_id = ?", (str(iid),)
        ).fetchone()
        return int(rowid)
    finally:
        con.close()


def tamper(path: Path, column: str, value: Any, rowid: int) -> None:
    """ "Linha adulterada": direct ``UPDATE outbox SET <coluna> = ? WHERE rowid = ?``."""
    assert re.fullmatch(r"[a-z_]+", column)
    con = sqlite3.connect(path)
    try:
        con.execute(f"UPDATE outbox SET {column} = ? WHERE rowid = ?", (value, rowid))  # noqa: S608
        con.commit()
        (stored_type,) = con.execute(
            f"SELECT typeof({column}) FROM outbox WHERE rowid = ?",  # noqa: S608
            (rowid,),
        ).fetchone()
    finally:
        con.close()
    expected = "blob" if isinstance(value, bytes) else "text"
    assert stored_type == expected, (column, stored_type)  # the affinity kept the bad type


def row_by_rowid(path: Path, rowid: int) -> dict[str, Any]:
    con = sqlite3.connect(path.absolute().as_uri() + "?mode=ro", uri=True)
    try:
        con.row_factory = sqlite3.Row
        return dict(con.execute("SELECT * FROM outbox WHERE rowid = ?", (rowid,)).fetchone())
    finally:
        con.close()


def status_of(path: Path, iid: uuid.UUID | str) -> str:
    return row_by_rowid(path, rowid_of(path, iid))["status"]


def make_dead_outbox(tmp_path: Path, n: int) -> tuple[Path, list[InspectionCreate]]:
    """A closed outbox with ``n`` dead items, created in this order (public API only)."""
    path = tmp_path / "outbox.sqlite3"
    clock = ManualClock(datetime(2026, 10, 1, 12, 0, tzinfo=UTC))
    outbox = SqliteOutbox(path, clock=clock, connectivity=ConnectivityState())
    items = []
    try:
        for _ in range(n):
            item = inspection()
            outbox.put(item)
            items.append(item)
            clock.advance(1)
        for item in items:
            outbox.mark_dead(item.inspection_id, REJECT_ERROR)
            clock.advance(1)
    finally:
        outbox.close()
    return path, items


def run_cli(argv: list[str]) -> int:
    try:
        value = qc_edge.requeue.main(argv)
    except SystemExit as exc:
        code = exc.code
        return code if isinstance(code, int) else (0 if code is None else 1)
    assert isinstance(value, int)
    return value


def log_text(caplog: pytest.LogCaptureFixture) -> str:
    """Every visible part of every record (message, raw msg, args, formatted exception)."""
    formatter = logging.Formatter()
    parts = [caplog.text]
    for record in caplog.records:
        parts += [record.getMessage(), str(record.msg), repr(record.args)]
        if record.exc_info:
            parts.append(formatter.formatException(record.exc_info))
        if record.exc_text:
            parts.append(record.exc_text)
    return "\n".join(parts)


def outbox_warnings(caplog: pytest.LogCaptureFixture) -> list[str]:
    return [
        r.getMessage()
        for r in caplog.records
        if r.name == OUTBOX_LOGGER and r.levelno == logging.WARNING
    ]


def assert_hidden(mark: str, *texts: str) -> None:
    for text in texts:
        assert mark not in text


