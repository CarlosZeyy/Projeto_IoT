def _raiser(exc: Exception) -> Callable[..., Any]:
    def fail(*args: Any, **kwargs: Any) -> Any:
        raise exc

    return fail


@pytest.mark.parametrize(
    ("method", "exc_type", "extra"),
    [("dead_items", ValueError, []), ("requeue_dead", TypeError, ["--yes"])],
    ids=["listing-ValueError", "requeue-TypeError"],
)
def test_ca04_value_and_type_errors_exit_1_without_message_or_traceback(
    tmp_path: Path,
    method: str,
    exc_type: type[Exception],
    extra: list[str],
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
    caplog: pytest.LogCaptureFixture,
) -> None:
    path, _ = make_dead_outbox(tmp_path, 1)
    mark = new_mark()
    monkeypatch.setattr(SqliteOutbox, method, _raiser(exc_type(mark)))
    caplog.set_level(logging.DEBUG)

