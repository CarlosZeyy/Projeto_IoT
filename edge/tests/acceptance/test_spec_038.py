def test_ca02_requeue_and_loop_never_stop_on_an_invalid_row(
    live_rig: Rig,
    capsys: pytest.CaptureFixture[str],
    caplog: pytest.LogCaptureFixture,
) -> None:
    rig = live_rig
    p1, p2, d1, d2 = (inspection() for _ in range(4))
    for item in (p1, p2, d1, d2):
        rig.outbox.put(item)
        rig.clock.advance(0.5)
    rig.outbox.mark_dead(d1.inspection_id, REJECT_ERROR)
    rig.outbox.mark_dead(d2.inspection_id, REJECT_ERROR)
    mark = new_mark()
    d2_rowid = rowid_of(rig.path, d2.inspection_id)
    tamper(rig.path, "created_at", mark, d2_rowid)
    caplog.set_level(logging.DEBUG)

    code = run_cli(["--outbox-path", str(rig.path), "--yes"])
    out, err = capsys.readouterr()
    assert code == 0, (out, err)
    assert out == "requeued 2 item(s)\n", out
    assert "Traceback" not in err

    caplog.clear()
    rig.clock.set(datetime.now(UTC) + timedelta(seconds=1))
    rig.drain(max_cycles=10)

    for item in (p1, p2, d1):
        assert status_of(rig.path, item.inspection_id) == "sent", item.inspection_id
    row = row_by_rowid(rig.path, d2_rowid)
    assert row["status"] == "dead"
    assert row["last_error"] == "invalid outbox row" == INVALID_ROW_ERROR
    assert row["created_at"] == mark
    expected = {str(i.inspection_id) for i in (p1, p2, d1)}
    assert set(rig.cloud.stored) == expected
    assert len(rig.cloud.writes) == len(set(rig.cloud.writes)) == 3  # 0 duplicated writes
    warnings = outbox_warnings(caplog)
    assert len(warnings) == 1, warnings
    assert f"rowid={d2_rowid}" in warnings[0] and "column=created_at" in warnings[0]
    assert warnings[0] == f"invalid outbox row marked dead (rowid={d2_rowid}, column=created_at)"
    logs = log_text(caplog)
    assert "publish cycle failed unexpectedly" not in logs
    assert_hidden(mark, logs, capsys.readouterr().err)

    batches_before = len(rig.cloud.batches)
    warnings_before = len(outbox_warnings(caplog))
    for _ in range(5):
        rig.clock.advance(120)
        rig.loop.run_once()
    assert len(rig.cloud.batches) == batches_before
    assert len(outbox_warnings(caplog)) == warnings_before


