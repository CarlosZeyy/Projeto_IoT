    assert len(warnings) == 1, warnings
    assert f"rowid={rowid}" in warnings[0]
    assert f"column={expected_column}" in warnings[0]
    # section 4.1: the fixed text of the warning
    assert warnings[0] == f"invalid dead row skipped (rowid={rowid}, column={expected_column})"
    assert_hidden(mark, out, err, log_text(caplog))
    assert "Traceback" not in err
    assert path.read_bytes() == before


