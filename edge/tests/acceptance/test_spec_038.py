    clock: Clock = field(default_factory=Clock)
    sleep: SleepSpy = field(default_factory=SleepSpy)

    def put(self, name: str, data: bytes, inbox: Path | None = None) -> str:
        target = (self.inbox if inbox is None else inbox) / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        return name

    def argv(self, *, inbox: Path | None = None, plan: Path | None = None) -> list[str]:
        return [
            "--dataset-dir",
            str(self.dataset),
            "--inbox",
            str(self.inbox if inbox is None else inbox),
            "--plan",
            str(self.plan if plan is None else plan),
            "--external-sources",
            str(self.registry),
            "--privacy-checked",
        ]

    def run(self, argv: list[str] | None = None) -> Result:
        self.capsys.readouterr()
        self.caplog.clear()
        with self.caplog.at_level(logging.DEBUG):
            try:
                code = qc_edge.importer.main(
                    self.argv() if argv is None else argv, clock=self.clock, sleep=self.sleep
                )
            except SystemExit as exc:
                raw = exc.code
                code = raw if isinstance(raw, int) else (0 if raw is None else 1)
        out = self.capsys.readouterr()
        return Result(code, out.out, out.err, self.caplog.text)

    def import_one(self, name: str, data: bytes, cells: Sequence[str]) -> Result:
        self.put(name, data)
        write_plan(self.plan, [row(name, cells)])
        result = self.run()
        assert result.code == 0, result.everything()
        return result

    @property
    def manifest(self) -> Path:
        return self.dataset / "manifest.csv"

    @property
    def sources(self) -> Path:
        return self.dataset / "sources.csv"

    def images(self) -> list[str]:
        raw = self.dataset / "raw"
        if not raw.exists():
            return []
        return sorted(str(p.relative_to(self.dataset)) for p in raw.rglob("*") if p.is_file())

    def dirs(self) -> dict[str, int]:
        """Every directory under ``DATASET_DIR`` (itself included) and its mode."""
        found = {".": stat.S_IMODE(self.dataset.stat().st_mode)}
        for p in self.dataset.rglob("*"):
            if p.is_dir() and not p.is_symlink():
                found[str(p.relative_to(self.dataset))] = stat.S_IMODE(p.stat().st_mode)
        return found


