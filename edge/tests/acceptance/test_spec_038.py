@pytest.mark.parametrize("case", list(CA01_CASES))
def test_ca01_listing_skips_the_invalid_row_without_echo(
    tmp_path: Path,
    case: str,
    capsys: pytest.CaptureFixture[str],
    caplog: pytest.LogCaptureFixture,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.delenv("DEVICE_API_KEY", raising=False)
    column, kind, expected_column = CA01_CASES[case]
    mark = new_mark()
    path, (d1, d2, d3) = make_dead_outbox(tmp_path, 3)
    rowid = rowid_of(path, d2.inspection_id)
    tamper(path, column, _ca01_value(kind, mark), rowid)
    before = path.read_bytes()
    caplog.set_level(logging.DEBUG)

    code = run_cli(["--outbox-path", str(path)])
    out, err = capsys.readouterr()

    assert code == 0, (out, err)
    lines = out.splitlines()
    assert len(lines) == 3, out
    assert lines[0].split(" ", 1)[0] == str(d1.inspection_id)
