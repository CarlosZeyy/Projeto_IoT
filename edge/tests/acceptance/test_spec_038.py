def _fd_name(fd: int) -> str:
    try:
        return os.readlink(f"/proc/self/fd/{fd}")
    except OSError:
        return ""


def enospc_when(monkeypatch: pytest.MonkeyPatch, match: Callable[[str], bool]) -> list[str]:
    """The spy of CA-09 of SPEC-036: ``os.write`` raises ENOSPC for a matching target.

    The image goes through a buffered file object (its bytes never pass through ``os.write``),
    so the spy also makes ``os.fsync`` of a matching regular file fail with ENOSPC, which is
    where a full disk shows up for buffered and delayed-allocation writes. Directories are
    never matched (their ``fsync`` is not a write)."""
    hits: list[str] = []
    real_write = os.write
    real_fsync = os.fsync

    def matching(fd: int) -> str | None:
        name = _fd_name(fd)
        if name and match(name) and not os.path.isdir(name):
            return name
        return None

    def write_spy(fd: int, data: Any) -> int:
        name = matching(fd)
        if name:
            hits.append(name)
            raise OSError(errno.ENOSPC, os.strerror(errno.ENOSPC))
        return real_write(fd, data)

    def fsync_spy(fd: Any) -> None:
        number = fd if isinstance(fd, int) else fd.fileno()
        name = matching(number)
        if name:
            hits.append(name)
            raise OSError(errno.ENOSPC, os.strerror(errno.ENOSPC))
        real_fsync(fd)

    monkeypatch.setattr(os, "write", write_spy)
    monkeypatch.setattr(os, "fsync", fsync_spy)
    return hits


